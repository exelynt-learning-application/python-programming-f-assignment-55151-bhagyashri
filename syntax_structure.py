# Program Title
print("Basic Python Structure Demonstration")

# Top-level print statements
print("This is the first print statement.")
print("This is the second print statement.")
print("This is the third print statement.")

# If statement with properly indented code
if True:  # The condition is true, so the block of code inside the if statement will run
    # Nested block inside the if statement
    print("This is inside the if block.")  # Indentation level 1
    if True:  # Another nested if statement
        print("This is inside the nested block.")  # Indentation level 2

# End of program
