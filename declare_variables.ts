// declare_variables.ts

// Declaring variables and assigning values

// Declaring a string variable
let userName: string = "Alice";

// Declaring a number variable
let age: number = 30;

// Declaring a boolean variable
let isStudent: boolean = false;

// Declaring an array of numbers
let scores: number[] = [90, 85, 88];

// Declaring an object with properties
let person: { name: string, age: number } = {
  name: "Bob",
  age: 25
};

// Logging the values of the variables
console.log("Name:", userName);          // Output: Name: Alice
console.log("Age:", age);            // Output: Age: 30
console.log("Is Student:", isStudent); // Output: Is Student: false
console.log("Scores:", scores);      // Output: Scores: [ 90, 85, 88 ]
console.log("Person:", person);      // Output: Person: { name: 'Bob', age: 25 }